pub fn dct_zero() -> Vlc { Vlc::from_strs(&[DCT_ZERO, DCT_SHARED].concat()) }
pub fn dct_one() -> Vlc { Vlc::from_strs(&[DCT_ONE, DCT_SHARED].concat()) }

/// A VDEC table as a decoder (values keep VDEC's length << 16)
pub fn vdec(entries: &[(u32, u32, u32)]) -> Vlc {
    let e: Vec<(u32, u32, i32)> = entries.iter().map(|&(c, l, v)| (c, l, v as i32)).collect();
    Vlc::new(&e)
}

