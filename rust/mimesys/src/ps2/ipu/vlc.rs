//! The IPU's variable-length codes.
//!
//! - MPEG-2 (ISO/IEC 13818-2 annex B) tables B.9 (coded block pattern), B.12 / B.13 (DC size),
//!   B.14 / B.15 (DCT coefficients), written out from the standard, as code strings
//! - VDEC's tables (macroblock address increment, macroblock types, motion code, dmvector)
//!   in the form VDEC returns them, (code length << 16) | value: from Play! (BSD-2-Clause,
//!   Jean-Philip Desjardins), Source/ee/IPU_*Table.cpp

/// A decoding table: indexed by the next `bits` bits, (code length, value); length 0 = no code
pub struct Vlc {
    pub bits: u32,
    pub lut: Vec<(u8, i32)>,
}

impl Vlc {
    /// From (code, length, value) entries
    pub fn new(entries: &[(u32, u32, i32)]) -> Self {
        let bits = entries.iter().map(|e| e.1).max().unwrap_or(1);
        let mut lut = vec![(0u8, 0i32); 1 << bits];
        for &(code, len, val) in entries {
            let shift = bits - len;
            let base = (code << shift) as usize;
            for k in 0..(1usize << shift) {
                assert!(lut[base + k].0 == 0, "VLC codes overlap");
                lut[base + k] = (len as u8, val);
            }
        }
        Self { bits, lut }
    }

    /// From ("0101", value) strings (spaces ignored)
    pub fn from_strs(entries: &[(&str, i32)]) -> Self {
        let parsed: Vec<(u32, u32, i32)> = entries.iter().map(|(s, v)| {
            let b: String = s.chars().filter(|c| *c == '0' || *c == '1').collect();
            (u32::from_str_radix(&b, 2).unwrap(), b.len() as u32, *v)
        }).collect();
        Self::new(&parsed)
    }
}

